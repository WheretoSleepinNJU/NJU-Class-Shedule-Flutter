            fun values(key: String): Map<String, Int> {
                val result = (args[key] as? Map<*, *>)?.entries?.mapNotNull { (name, value) ->
                    if (name is String && value is Number) name to value.toInt() else null
                }?.toMap().orEmpty().toMutableMap()
                // Compatible with older bridge configurations.
                for (name in listOf("primary", "surface", "onSurface")) {
                    if (!result.containsKey(name)) (args[name] as? Number)?.let { result[name] = it.toInt() }
                }
                return result
            }
            return AdaptiveNativePalette(values("materialColors"), values("miuixColors"))
        }
    }
